const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  list: () => ipcRenderer.invoke('courses:list'),
  get: (id) => ipcRenderer.invoke('courses:get', id),
  save: (c) => ipcRenderer.invoke('courses:save', c),
  remove: (id) => ipcRenderer.invoke('courses:delete', id),
  refreshCourse: (id) => ipcRenderer.invoke('courses:refresh', id),
  importPlaylist: (url) => ipcRenderer.invoke('courses:import', url),
  resolveVideos: (text) => ipcRenderer.invoke('videos:resolve', text),
  exportData: (prefs) => ipcRenderer.invoke('data:export', prefs),
  importData: () => ipcRenderer.invoke('data:import'),
  openDataFolder: () => ipcRenderer.invoke('data:folder'),
  playerOp: (op, arg) => ipcRenderer.invoke('player:op', op, arg),
  dnd: (on) => ipcRenderer.invoke('dnd:set', on),
  dlList: (cid) => ipcRenderer.invoke('dl:list', cid),
  dlStart: (cid, vids) => ipcRenderer.invoke('dl:start', cid, vids),
  dlCancel: (cid, vid) => ipcRenderer.invoke('dl:cancel', cid, vid),
  dlDelete: (cid, vid) => ipcRenderer.invoke('dl:delete', cid, vid),
  dlOpen: (cid) => ipcRenderer.invoke('dl:open', cid),
  onDlProgress: (cb) => ipcRenderer.on('dl:progress', (_e, p) => cb(p)),
  chapters: (vid) => ipcRenderer.invoke('chapters:get', vid),
  openExternal: (u) => ipcRenderer.invoke('open-external', u),
  onStatus: (cb) => ipcRenderer.on('import-status', (_e, m) => cb(m)),
  onIncomingUrl: (cb) => ipcRenderer.on('incoming-url', (_e, u) => cb(u)),
});
